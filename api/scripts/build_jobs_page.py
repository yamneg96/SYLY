"""Build the demo jobs page and its assistant content from demo/data/jobs.json (FR-J1, FR-T11).

    python api/scripts/build_jobs_page.py

Writes:
  savanna/pages/jobs.html          our page (not a starter file): job cards + one JobPosting JSON-LD per job
  demo/data/jobs-content.json      the jobs as citable sections for <db-assistant content="...">

Static HTML on purpose: validators and search engines read the JSON-LD without running JavaScript.
"""

from __future__ import annotations

import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "api"))

from services.jobs_format import job_to_section, jsonld  # noqa: E402

TYPES = {"FULL_TIME": "Full time", "PART_TIME": "Part time", "CONTRACTOR": "Contract", "TEMPORARY": "Temporary"}


def e(s: object) -> str:
    return html.escape(str(s or ""), quote=True)


def card(job: dict) -> str:
    jid = job["id"]
    acc = "".join(
        f'<li>{e(en)}{f" <span lang=\"am\">({e(am)})</span>" if am else ""}</li>'
        for en, am in zip(job.get("accommodations_en", []), job.get("accommodations_am", []) + [""] * 10)
    )
    remote = " · Remote possible" if job.get("remote") else ""
    keyword = (job.get("keywords_en") or [job["title_en"]])[0]
    ld = json.dumps(jsonld(job), ensure_ascii=False, indent=2).replace("</", "<\\/")
    return f"""
      <article class="job" id="job-{e(jid)}" aria-labelledby="job-{e(jid)}-title">
        <h2 id="job-{e(jid)}-title" tabindex="-1">{e(job['title_en'])} <span lang="am" class="am">{e(job.get('title_am'))}</span></h2>
        <dl>
          <div><dt>Employer</dt><dd>{e(job['employer'])}</dd></div>
          <div><dt>Location</dt><dd>{e(job['location_en'])} <span lang="am">({e(job.get('location_am'))})</span>{remote}</dd></div>
          <div><dt>Type</dt><dd>{e(TYPES.get(job.get('employment_type', ''), job.get('employment_type')))}</dd></div>
          <div><dt>Apply by</dt><dd><time datetime="{e(job['deadline'])}">{e(job['deadline'])}</time>
            <span lang="am" class="eth-date" data-date="{e(job['deadline'])}"></span>
            <span class="passed" data-deadline="{e(job['deadline'])}" hidden>(deadline passed)</span></dd></div>
        </dl>
        <p>{e(job['summary_en'])}</p>
        <p lang="am">{e(job.get('summary_am'))}</p>
        <p>{e(job.get('requirements_en'))}</p>
        <h3>Support this employer offers</h3>
        <ul>{acc}</ul>
        <div class="actions">
          <button type="button" class="act" data-action="ask" data-job="{e(jid)}" data-title-en="{e(job['title_en'])}" data-title-am="{e(job.get('title_am'))}">Ask about this job</button>
          <button type="button" class="act" data-action="support" data-job="{e(jid)}" data-title-en="{e(job['title_en'])}" data-title-am="{e(job.get('title_am'))}">Request interview support</button>
          <button type="button" class="act" data-action="alerts" data-keyword="{e(keyword)}">Get alerts like this</button>
        </div>
        <script type="application/ld+json">
{ld}
        </script>
      </article>"""


def page(jobs: list[dict]) -> str:
    cards = "".join(card(j) for j in jobs)
    return f"""<!doctype html>
<!--
  Demo jobs page for the SYLY career gateway (Track 3). NOT a starter file: generated by
  api/scripts/build_jobs_page.py from demo/data/jobs.json. TEST DATA ONLY.
-->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Jobs for learners (test data) | G-School Intranet</title>
    <link rel="stylesheet" href="../assets/css/typekit-xgz4ilr-css.css" />
    <link rel="stylesheet" href="../assets/css/application_alx.css" media="all" />
    <link rel="stylesheet" href="../assets/css/app.css" media="all" />
    <style>
      /* Our page only. Savanna's #db3e3e primary is 4.4:1 on white, so buttons use #002B56. */
      .skip {{ position: absolute; inset-inline-start: 0.5rem; top: -10rem; padding: 0.75rem 1rem; background: #002B56; color: #FFFFFF; z-index: 10; }}
      .skip:focus {{ top: 0.5rem; }}
      .jobs-main {{ max-width: 52rem; margin: 0 auto; padding: 1.5rem 1rem 6rem; color: #111111; }}
      .jobs-main h1 {{ font-size: 1.75rem; }}
      .job {{ border: 2px solid #767676; border-radius: 0.75rem; padding: 1rem; margin-block: 1rem; }}
      .job h2 {{ font-size: 1.375rem; }}
      .job h2 .am {{ display: block; font-size: 1.125rem; font-weight: 400; }}
      .job h3 {{ font-size: 1.0625rem; margin-top: 0.75rem; }}
      .job dl {{ display: grid; gap: 0.25rem; margin: 0.5rem 0; }}
      .job dl div {{ display: flex; flex-wrap: wrap; gap: 0.5rem; }}
      .job dt {{ font-weight: 600; }}
      .job dd {{ margin: 0; }}
      [lang|="am"] {{ line-height: 1.7; letter-spacing: normal; text-transform: none; }}
      .actions {{ display: flex; flex-wrap: wrap; gap: 0.5rem; margin-top: 0.75rem; }}
      .act {{ min-height: 2.75rem; padding: 0.5rem 1rem; border-radius: 0.5rem; font: inherit; font-weight: 600; cursor: pointer;
             background: #002B56; color: #FFFFFF; border: 2px solid #002B56; }}
      .act + .act {{ background: #FFFFFF; color: #111111; border-color: #767676; }}
      a {{ color: #111111; text-decoration: underline; }}
      :focus-visible {{ outline: 3px solid #F5A300; outline-offset: 2px; box-shadow: 0 0 0 2px #111111; }}
      .notice {{ border-inline-start: 0.375rem solid #111111; padding: 0.5rem 0.75rem; background: #F2F2F2; }}
    </style>
  </head>
  <body>
    <a class="skip" href="#main">Skip to main content</a>
    <main id="main" class="jobs-main">
      <p><a href="concept-with-navigation.html">Back to the lesson</a></p>
      <h1>Jobs for learners <span lang="am">(ለተማሪዎች የሚሆኑ ሥራዎች)</span></h1>
      <p class="notice"><strong>Test data only.</strong> These employers and jobs are made up for the hackathon demo.
        Interview support requests go to a career helper, never straight to the employer, and nobody asks for proof.</p>
{cards}
    </main>

    <script>
      // Host page script: Ethiopian calendar dates (NFR-E3) and the three job buttons.
      (function () {{
        var today = new Date().toISOString().slice(0, 10);
        document.querySelectorAll('.eth-date').forEach(function (el) {{
          try {{
            el.textContent = '(' + new Intl.DateTimeFormat('am-ET-u-ca-ethiopic', {{ day: 'numeric', month: 'long', year: 'numeric' }})
              .format(new Date(el.getAttribute('data-date') + 'T12:00:00')) + ')';
          }} catch (e) {{ /* browser without Ethiopian calendar: Gregorian date stays */ }}
        }});
        document.querySelectorAll('.passed').forEach(function (el) {{ el.hidden = el.getAttribute('data-deadline') >= today; }});
        document.addEventListener('click', function (e) {{
          var b = e.target.closest('button.act');
          var el = document.querySelector('db-assistant');
          if (!b || !el || !el.ask) return;
          var lang = el.getAttribute('lang') === 'am' ? 'am' : 'en';
          var title = b.getAttribute('data-title-' + lang) || b.getAttribute('data-title-en');
          var a = b.getAttribute('data-action');
          if (a === 'ask') el.ask(el.getText('jobAsk').replace('{{title}}', title));
          if (a === 'support') el.openAccommodation({{ id: b.getAttribute('data-job'), title: title }});
          if (a === 'alerts') el.showJobAlerts(b.getAttribute('data-keyword'));
        }});
      }})();
    </script>
    <!-- SYLY db-assistant with the jobs as its content (FR-T11) -->
    <script src="/module/db-assistant.js" defer></script>
    <db-assistant lang="am" api="/api" content="/demo/data/jobs-content.json"></db-assistant>
  </body>
</html>
"""


def main() -> None:
    data = json.loads((ROOT / "demo/data/jobs.json").read_text(encoding="utf-8"))
    jobs = data["jobs"]
    (ROOT / "savanna/pages/jobs.html").write_text(page(jobs), encoding="utf-8")
    sections = [job_to_section(j) for j in jobs]
    out = {"notice": data.get("notice", ""), "sections": sections}
    (ROOT / "demo/data/jobs-content.json").write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"jobs.html and jobs-content.json written for {len(jobs)} jobs")


if __name__ == "__main__":
    main()
